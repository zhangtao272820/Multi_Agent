def main() -> None:
    changed = 0
    for path in sorted(EVENTS.glob("story_*.yaml")):
        text = path.read_text(encoding="utf-8")
        orig = text
        for old, new in REPLACEMENTS:
            if old in text:
                text = text.replace(old, new)
        if text != orig:
            # re-dump via yaml to keep structure? Better keep raw replace to avoid reformatting whole file again
            path.write_text(text, encoding="utf-8")
            changed += 1
            # validate still parses
            yaml.safe_load(text)
    print(f"files updated: {changed}")


if __name__ == "__main__":
    main()
